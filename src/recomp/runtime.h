// ---- memory
extern u8* g_base;
inline u8 r8(u32 a) { return g_base[a]; }
inline u16 r16(u32 a) { u16 v; std::memcpy(&v, g_base + a, 2); return v; }
inline u32 r32(u32 a) { u32 v; std::memcpy(&v, g_base + a, 4); return v; }
inline void w8(u32 a, u8 v) { g_base[a] = v; }
