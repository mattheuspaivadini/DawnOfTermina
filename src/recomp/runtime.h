// ---- integer flags
inline u32 add_flags(Context* c, u32 a, u32 b) {
    const u64 r = u64(a) + b;
    const u32 res = u32(r);
    c->n = res >> 31, c->z = res == 0, c->c = u32(r >> 32), c->v = (~(a ^ b) & (a ^ res)) >> 31;
    return res;
}
inline u32 adc_flags(Context* c, u32 a, u32 b) {
    const u64 r = u64(a) + b + c->c;
    const u32 res = u32(r);
    c->n = res >> 31, c->z = res == 0, c->c = u32(r >> 32), c->v = (~(a ^ b) & (a ^ res)) >> 31;
    return res;
}
inline u32 sub_flags(Context* c, u32 a, u32 b) {
    const u32 res = a - b;
    c->n = res >> 31, c->z = res == 0, c->c = a >= b, c->v = ((a ^ b) & (a ^ res)) >> 31;
    return res;
}
inline u32 sbc_flags(Context* c, u32 a, u32 b) {
    const u64 r = u64(a) + u64(~b) + c->c;
    const u32 res = u32(r);
    c->n = res >> 31, c->z = res == 0, c->c = u32(r >> 32), c->v = ((a ^ b) & (a ^ res)) >> 31;
    return res;
}

// Register-specified shift (amount = Rs[7:0]); type 0 LSL, 1 LSR, 2 ASR, 3 ROR.
inline u32 shift_reg(u32 type, u32 v, u32 amt, u32 cin, u32* cout) {
    if (amt == 0) return *cout = cin, v;
    switch (type) {
    case 0:
        if (amt < 32) return *cout = (v >> (32 - amt)) & 1, v << amt;
        return *cout = amt == 32 ? v & 1 : 0, 0;
    case 1:
        if (amt < 32) return *cout = (v >> (amt - 1)) & 1, v >> amt;
        return *cout = amt == 32 ? v >> 31 : 0, 0;
    case 2:
        if (amt < 32) return *cout = (v >> (amt - 1)) & 1, u32(s32(v) >> amt);
        return *cout = v >> 31, u32(s32(v) >> 31);
    default:
        if ((amt & 31) == 0) return *cout = v >> 31, v;
        return *cout = (v >> ((amt & 31) - 1)) & 1, std::rotr(v, int(amt & 31));
    }
}

