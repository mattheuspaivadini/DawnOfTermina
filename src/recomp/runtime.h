// ---- VFP
inline float fs(const Context* c, u32 i) { return std::bit_cast<float>(c->s[i]); }
inline void set_fs(Context* c, u32 i, float v) { c->s[i] = std::bit_cast<u32>(v); }
inline double fd(const Context* c, u32 i) {
    return std::bit_cast<double>(u64(c->s[2 * i]) | u64(c->s[2 * i + 1]) << 32);
}
inline void set_fd(Context* c, u32 i, double v) {
    const u64 b = std::bit_cast<u64>(v);
    c->s[2 * i] = u32(b), c->s[2 * i + 1] = u32(b >> 32);
}
void vfp_cmp(Context* c, double a, double b);
inline void fmstat(Context* c) {
    c->n = c->fpscr >> 31, c->z = c->fpscr >> 30 & 1, c->c = c->fpscr >> 29 & 1, c->v = c->fpscr >> 28 & 1;
}
